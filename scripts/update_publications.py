#!/usr/bin/env python3
"""
Fetch the publications in my NASA/ADS library and save them to
data/publications.json, plus a copy as data/publications.js that
publications.html loads (a <script> also works when the page is opened
straight from disk, where browsers block reading .json files).

Usage:
    ADS_API_TOKEN=<your token> python3 scripts/update_publications.py

Get a token at https://ui.adsabs.harvard.edu/user/settings/token
The GitHub Action in .github/workflows/update-publications.yml runs this
weekly using the repository secret ADS_API_TOKEN.

Only the Python standard library is used, so nothing needs installing.
"""
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

LIBRARY_ID = "8JBeznfWQmWUeiV-poEimw"
API = "https://api.adsabs.harvard.edu/v1"
FIELDS = ("bibcode,title,author,year,pubdate,pub,volume,page,doi,"
          "identifier,doctype,property,citation_count,abstract")
OUT = Path(__file__).resolve().parent.parent / "data" / "publications.json"
OUT_JS = OUT.with_suffix(".js")


def ads_request(path, token, params=None, body=None):
    url = f"{API}/{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params)
    headers = {"Authorization": f"Bearer {token}"}
    data = None
    if body is not None:
        data = body.encode()
        headers["Content-Type"] = "big-query/csv"
    req = urllib.request.Request(url, data=data, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            return json.load(resp)
    except urllib.error.HTTPError as err:
        if err.code == 401:
            sys.exit("ADS rejected the token (401 Unauthorized). Check that "
                     "ADS_API_TOKEN holds your own token from "
                     "https://ui.adsabs.harvard.edu/user/settings/token")
        if err.code == 403:
            sys.exit("ADS refused access to the library (403). Make sure the "
                     "library is public, or that the token belongs to its owner.")
        raise


def library_bibcodes(token):
    """All bibcodes in the library (the API pages through them)."""
    bibcodes, start, rows = [], 0, 500
    while True:
        res = ads_request(f"biblib/libraries/{LIBRARY_ID}", token,
                          {"start": start, "rows": rows})
        docs = res.get("documents", [])
        bibcodes += docs
        total = res.get("metadata", {}).get("num_documents", len(bibcodes))
        start += rows
        if not docs or len(bibcodes) >= total:
            return bibcodes


def fetch_records(bibcodes, token):
    body = "bibcode\n" + "\n".join(bibcodes)
    res = ads_request("search/bigquery", token,
                      {"q": "*:*", "fl": FIELDS, "rows": 2000}, body=body)
    return res["response"]["docs"]


def arxiv_id(identifiers):
    for ident in identifiers or []:
        if ident.lower().startswith("arxiv:"):
            return ident.split(":", 1)[1]
    return None


def simplify(doc):
    """Keep only what the page needs, with friendly field names."""
    page = doc.get("page") or []
    return {
        "bibcode": doc["bibcode"],
        "title": (doc.get("title") or [""])[0],
        "authors": doc.get("author", []),
        "year": int(doc.get("year", 0)),
        "pubdate": doc.get("pubdate", ""),
        "journal": doc.get("pub", ""),
        "volume": doc.get("volume"),
        "page": page[0] if page else None,
        "doi": (doc.get("doi") or [None])[0],
        "arxiv": arxiv_id(doc.get("identifier")),
        "doctype": doc.get("doctype", ""),
        "refereed": "REFEREED" in (doc.get("property") or []),
        "citations": doc.get("citation_count"),
        "abstract": doc.get("abstract"),
    }


def write_js():
    """Mirror publications.json as a script that sets window.PUBLICATIONS."""
    data = json.loads(OUT.read_text())
    OUT_JS.write_text(
        "// Generated by scripts/update_publications.py - do not edit by hand.\n"
        "window.PUBLICATIONS = "
        + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")


def main():
    token = os.environ.get("ADS_API_TOKEN")
    if not token:
        sys.exit("Set the ADS_API_TOKEN environment variable "
                 "(https://ui.adsabs.harvard.edu/user/settings/token).")

    bibcodes = library_bibcodes(token)
    papers = [simplify(d) for d in fetch_records(bibcodes, token)]
    papers.sort(key=lambda p: (p["pubdate"], p["bibcode"]), reverse=True)

    # Leave the file alone when nothing changed, so the weekly GitHub Action
    # does not commit just because the date moved on.
    if OUT.exists():
        old = json.loads(OUT.read_text()).get("papers")
        if old == papers:
            print(f"No changes ({len(papers)} publications).")
            write_js()
            return

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps({
        "source": f"https://ui.adsabs.harvard.edu/public-libraries/{LIBRARY_ID}",
        "updated": date.today().isoformat(),
        "papers": papers,
    }, indent=1, ensure_ascii=False) + "\n")
    write_js()
    print(f"Saved {len(papers)} publications to {OUT}")


if __name__ == "__main__":
    main()
